const inMainland = ([lon, lat]) => lon > -74.5 && lon < -53 && lat > -56 && lat < -21;

const geo = JSON.parse(readFileSync(new URL('./data/argentina-adm1.geojson', import.meta.url), 'utf8'));

// Keep only polygons inside the continental bounding box and with meaningful area.
const features = geo.features.map((f) => {
  const raw = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  // Source rings are clockwise; d3-geo expects counter-clockwise exteriors.
  const polys = raw.map((p) => p.map((ring) => [...ring].reverse()));
  const kept = polys.filter((p) => {
    const poly = { type: 'Polygon', coordinates: p };
    return inMainland(geoCentroid(poly)) && geoArea(poly) > 2e-6;
  });
  return { ...f, geometry: { type: 'MultiPolygon', coordinates: kept } };
});

const collection = { type: 'FeatureCollection', features };
const projection = geoConicConformal().parallels([-28, -48]).rotate([64, 0]).fitSize([WIDTH, HEIGHT], collection);

const ringToPath = (ring) => {
  const out = [];
  let last = null;
  for (const pt of ring) {
    const p = projection(pt);
    if (!p) continue;
    if (last && Math.hypot(p[0] - last[0], p[1] - last[1]) < MIN_STEP) continue;
    out.push(p);
    last = p;
  }
  if (out.length < 3) return '';
  return 'M' + out.map(([x, y]) => `${x.toFixed(1)},${y.toFixed(1)}`).join('L') + 'Z';
};

const provinces = features.map((f) => {
  const [id, name] = SLUGS[f.properties.shapeName];
  const d = f.geometry.coordinates.map((poly) => poly.map(ringToPath).join('')).join('');
  const [cx, cy] = projection(geoCentroid(f));
  return { id, name, d, cx: +cx.toFixed(1), cy: +cy.toFixed(1) };
});

const cities = CITIES.map(([provinceId, name, lon, lat]) => {
  const [x, y] = projection([lon, lat]);
  return { provinceId, name, x: +x.toFixed(1), y: +y.toFixed(1) };
});

