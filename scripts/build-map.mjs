const body = `export interface ProvinceShape { id: string; name: string; d: string; cx: number; cy: number }
export const MAP_WIDTH = ${WIDTH};
export const MAP_HEIGHT = ${HEIGHT};
export const PROVINCE_SHAPES: ProvinceShape[] = ${JSON.stringify(provinces)};
`;
writeFileSync(new URL('../src/data/argentina-map.ts', import.meta.url), header + body);
